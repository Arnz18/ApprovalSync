/**
 * ApprovalSync — Deterministic Synthetic OCR Provider Adapter
 * Milestone: DOC-02
 *
 * Provides a verified, deterministic OCR test double and baseline processor
 * that extracts machine-readable text and tokens from digital PDFs and synthetic fixtures,
 * assigns reproducible spatial bounding boxes, and models operational failure modes.
 */

import { Injectable, Logger } from '@nestjs/common';
import {
  IOcrProvider,
  OcrExtractionResult,
  OcrPage,
  OcrProcessingOptions,
  OcrToken,
} from '../interfaces/ocr-provider.interface';

@Injectable()
export class DeterministicOcrAdapter implements IOcrProvider {
  private readonly logger = new Logger(DeterministicOcrAdapter.name);

  public readonly providerId = 'SYNTHETIC_DETERMINISTIC_OCR_ADAPTER';
  public readonly isLiveProviderConfigured = true;

  /**
   * Extracts text, lines, and spatial tokens from a document buffer.
   */
  async extractTextAndTokens(
    fileBuffer: Buffer,
    mimeType: string,
    options?: OcrProcessingOptions,
  ): Promise<OcrExtractionResult> {
    const startTime = Date.now();

    // 1. Evaluate simulated failure conditions for negative tests
    if (options?.simulateTimeout) {
      throw new Error(
        'OCR engine timeout: processing exceeded maximum threshold of 10000ms.',
      );
    }

    if (options?.simulateCorruptedFile) {
      throw new Error(
        'Unrecoverable file corruption: cannot parse document xref table or stream dictionary.',
      );
    }

    if (!fileBuffer || fileBuffer.length === 0) {
      throw new Error('Cannot perform OCR: empty file buffer received.');
    }

    // 2. Extract raw text from the document buffer
    const rawText = this.extractTextFromBuffer(fileBuffer, mimeType);

    if (rawText.trim().length === 0) {
      throw new Error(
        'Unreadable document: no extractable text or glyph streams found in document.',
      );
    }

    // 3. Tokenize text into pages, lines, and spatial bounding boxes
    const lines = rawText
      .split(/\r?\n/)
      .filter((line) => line.trim().length > 0);
    const pages: OcrPage[] = [];
    const allTokens: OcrToken[] = [];

    const defaultPageWidth = 612; // Standard US Letter points
    const defaultPageHeight = 792;
    const linesPerPage = 25;
    const totalPages = Math.max(1, Math.ceil(lines.length / linesPerPage));

    const baseConfidence = options?.simulateLowConfidence ? 0.72 : 0.94;

    for (let pageIdx = 0; pageIdx < totalPages; pageIdx++) {
      const pageNumber = pageIdx + 1;
      const pageLines = lines.slice(
        pageIdx * linesPerPage,
        (pageIdx + 1) * linesPerPage,
      );
      const pageTokens: OcrToken[] = [];

      for (let lineIdx = 0; lineIdx < pageLines.length; lineIdx++) {
        const line = pageLines[lineIdx];
        const words = line.split(/\s+/).filter((w) => w.length > 0);

        const yMin = 50 + lineIdx * 28;
        const yMax = yMin + 20;

        let currentX = 50;
        for (const word of words) {
          const wordWidth = Math.max(20, word.length * 7);
          const xMin = currentX;
          const xMax = currentX + wordWidth;
          currentX = xMax + 10;

          // Subtle variation in confidence without falling below threshold unless requested
          const jitter = ((word.length % 5) - 2) * 0.01;
          const tokenConfidence = Math.max(
            0.5,
            Math.min(0.99, Number((baseConfidence + jitter).toFixed(3))),
          );

          const token: OcrToken = {
            text: word,
            confidence: tokenConfidence,
            pageNumber,
            boundingBox: {
              pageNumber,
              xMin,
              yMin,
              xMax,
              yMax,
            },
          };

          pageTokens.push(token);
          allTokens.push(token);
        }
      }

      pages.push({
        pageNumber,
        text: pageLines.join('\n'),
        width: defaultPageWidth,
        height: defaultPageHeight,
        confidence: baseConfidence,
        tokens: pageTokens,
      });
    }

    // Calculate composite document confidence
    const confidenceScore =
      allTokens.length > 0
        ? Number(
            (
              allTokens.reduce((sum, t) => sum + t.confidence, 0) /
              allTokens.length
            ).toFixed(3),
          )
        : baseConfidence;

    const processingTimeMs = Date.now() - startTime;

    return {
      rawText,
      tokens: allTokens,
      pages,
      confidenceScore,
      providerMetadata: {
        providerId: this.providerId,
        isMock: true,
        engineVersion: '1.0.0-synthetic',
        processingTimeMs,
        modelInfo: 'Deterministic Rule-Based Synthetic OCR Engine',
        disclaimer:
          'This output was generated by the ApprovalSync deterministic OCR test double for synthetic demo and automated test evaluation.',
      },
    };
  }

  /**
   * Internal text extractor for synthetic PDFs, UTF-8 buffers, and plain text.
   */
  private extractTextFromBuffer(fileBuffer: Buffer, mimeType: string): string {
    void mimeType;
    const rawContent = fileBuffer.toString('utf8');

    // 1. If buffer contains PDF text streams (e.g. BT ... ET blocks)
    const streamRegex = /stream[\r\n]+([\s\S]*?)[\r\n]+endstream/g;
    let match: RegExpExecArray | null;
    const extractedStreamChunks: string[] = [];

    while ((match = streamRegex.exec(rawContent)) !== null) {
      const streamBody = match[1];
      // Search for text showing operators: (Some Text) Tj or [(Some) 10 (Text)] TJ
      const tjMatches = streamBody.match(/\(([^)]+)\)\s*(?:Tj|'|")/g);
      if (tjMatches && tjMatches.length > 0) {
        for (const item of tjMatches) {
          const cleanText = item
            .replace(/^\(/, '')
            .replace(/\)\s*(?:Tj|'|")$/, '');
          extractedStreamChunks.push(cleanText);
        }
      } else {
        // Look for printable text inside stream
        const readableChars = streamBody.replace(/[^\x20-\x7E\r\n\t]/g, '');
        if (readableChars.trim().length > 10) {
          extractedStreamChunks.push(readableChars);
        }
      }
    }

    if (extractedStreamChunks.length > 0) {
      return extractedStreamChunks.join('\n');
    }

    // 2. Extract ASCII text snippets from printable bytes
    const printableOnly = rawContent.replace(/[^\x20-\x7E\r\n\t]/g, ' ');
    const meaningfulLines = printableOnly
      .split(/\r?\n/)
      .map((l) => l.trim())
      .filter(
        (l) =>
          l.length >= 3 &&
          !l.startsWith('%') &&
          !l.startsWith('xref') &&
          !l.startsWith('trailer') &&
          !l.startsWith('startxref') &&
          !/^\d+\s+\d+\s+(?:obj|R)/.test(l) &&
          !/^(?:endobj|endstream|stream)$/.test(l),
      );

    if (meaningfulLines.length > 0) {
      return meaningfulLines.join('\n');
    }

    // 3. Fallback: unreadable
    return '';
  }
}
